    private void btn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn1ActionPerformed

        String datoComboBox = comboBox1.getSelectedItem().toString();
        if(datoComboBox.equals("ABB")){
            arbolLibro= new ArbolBinarioBusqueda<>();
            arbolPersona= new ArbolBinarioBusqueda<>();
            arbolPrestamo= new ArbolBinarioBusqueda<>();
            esBinario = true;
        }else{
            if(datoComboBox.equals("AVL")){
                arbolLibro = new ArbolesAVL<>();
                arbolPersona = new ArbolesAVL<>();
                arbolPrestamo = new ArbolesAVL<>();
                esBinario = true;
            }else{
                if(datoComboBox.equals("AMV")){
                    arbolLibro = new ArbolMViasBusqueda<>(4);
                    arbolPersona = new ArbolMViasBusqueda<>(4);   
                    arbolPrestamo = new ArbolMViasBusqueda<>(4);
                    esBinario = false;
                }else{
                    if(datoComboBox.equals("AB")){
                        arbolLibro = new ArbolB<>(4);
                        arbolPersona = new ArbolB<>(4); 
                        arbolPrestamo = new ArbolB<>(4);
                        esBinario = false;
                    }
                }
            }
        }
         // Crear y mostrar JFrame5
        jFrame5.setVisible(true);
        jFrame5.pack();
        //jFrame5.setExtendedState(JFrame.MAXIMIZED_BOTH); // maximizado
        jFrame5.setLocationRelativeTo(null);
        this.dispose();
        this.actualizarLabel();
    }//GEN-LAST:event_btn1ActionPerformed

    private void actualizarLabel(){
       if(esBinario){
            int cantidadLibros = arbolLibro.size();
            int cantidadPersonas = arbolPersona.size();
            int cantidadPrestamos = arbolPrestamo.size();
            jLabelLibros.setText(String.valueOf(cantidadLibros));
            jLabelPersonas.setText(String.valueOf(cantidadPersonas));
            jLabelPrestamos.setText(String.valueOf(cantidadPrestamos));
       }else{
           int cantidadLibros = arbolLibro.cantidadDeDatos();
            int cantidadPersonas = arbolPersona.cantidadDeDatos();
            int cantidadPrestamos = arbolPrestamo.cantidadDeDatos();
            jLabelLibros.setText(String.valueOf(cantidadLibros));
            jLabelPersonas.setText(String.valueOf(cantidadPersonas));
            jLabelPrestamos.setText(String.valueOf(cantidadPrestamos));
       }
    }
    
