    private void jButton25ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton25ActionPerformed
        int id = Integer.parseInt(jTextPane4.getText());
        int idPersona = Integer.parseInt(jTextPane10.getText());
        int idLibro = Integer.parseInt(jTextPane11.getText());
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
        Date fechaDevolucion = null;
       try {
            fechaDevolucion = sdf.parse(jTextPaneFechaDevolucion.getText().trim());
    
        } catch (ParseException ex) {
            JOptionPane.showMessageDialog(this, "Error: Formato de fecha inválido. Use dd/MM/yyyy");
        }
        NodoPrestamo nuevoPrestamo = new NodoPrestamo(id, idPersona, idLibro);
        nuevoPrestamo.setFechaDevolucion(fechaDevolucion);
        try {
            arbolPrestamo.insertar(nuevoPrestamo);
            JOptionPane.showMessageDialog(this, "Prestamo creado exitosamente");
        } catch (ExcepcionDatoYaExiste ex) {
            Logger.getLogger(Pantalla.class.getName()).log(Level.SEVERE, null, ex);
        }
        this.actualizarTablaPrestamos();
        this.actualizarLabel();
    }//GEN-LAST:event_jButton25ActionPerformed

