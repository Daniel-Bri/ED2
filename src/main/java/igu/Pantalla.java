    private void actualizarTabla() {
    List<NodoLibro> libros = arbolLibro.recorridoEnInOrden();
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    for (NodoLibro libro : libros) {
        model.addRow(new Object[]{
            libro.getId(),
            libro.getTitulo(),
            libro.getAutor(),
            libro.getAño(),
            libro.esDisponible() ? "Sí" : "No"
        });
    }
}

    
